def build_system_prompt(personality_key: str, birthday: str = "") -> str:
    """Собирает финальный system prompt с учётом контекста клиента."""
    p = PERSONALITIES.get(personality_key)
    if not p:
        return PSYCHOLOGIST_SYSTEM
    prompt = p["system_prompt"]
    if p["uses_birthday"] and birthday and "заполнить" not in birthday.lower():
        prompt += (
            f"\n\nКОНТЕКСТ КЛИЕНТА:\n"
            f"Дата рождения клиента: {birthday}\n"
            "Учитывай это согласно своим инструкциям по чтению натальной карты."
        )
    elif p["ask_birthday_if_missing"]:
        prompt += (
            "\n\nКОНТЕКСТ КЛИЕНТА:\n"
            "Дата рождения клиента — не указана.\n"
            "В первой же реплике спроси у клиента: какая у него дата рождения? "
            "Если знает время и место — попроси и их, но если знает только дату — этого достаточно."
        )
    return prompt
